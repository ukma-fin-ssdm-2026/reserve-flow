_DISABLE_VALUES = {"0", "false", "no", "off"}


def _export_openapi_on_startup(app: FastAPI) -> None:
    """Експортує OpenAPI-схему на старті, якщо це не вимкнено через EXPORT_OPENAPI=0 (Лаб 9, №10).

    Помилки файлової системи або відсутні внутрішні залежності (напр. yaml) логуються
    зі стеком через logging.exception, але не зупиняють старт сервера (контрольована деградація).
    """
    if os.getenv("EXPORT_OPENAPI", "1").strip().lower() in _DISABLE_VALUES:
        logging.info("Експорт OpenAPI пропущено (EXPORT_OPENAPI вимкнено).")
        return

    try:
        from export_openapi import export_openapi
    except ImportError as exc:
        if getattr(exc, "name", None) in (None, "export_openapi"):
            logging.warning("Модуль export_openapi не знайдено. Експорт пропущено.")
        else:
            logging.exception("Помилка експорту OpenAPI (відсутня залежність): %s", exc)
        return

    try:
        export_openapi(app)
        logging.info("OpenAPI специфікацію успішно експортовано.")
    except Exception as exc:
        logging.exception("Помилка експорту OpenAPI: %s", exc)


@asynccontextmanager
async def lifespan(app: FastAPI):
    """L4-08: Життєвий цикл застосунку. Перевірка конфігурації й експорт OpenAPI при старті."""
    # Лаб 9, №8: некоректна конфігурація зупиняє старт, а не ламає запити пізніше
    try:
        validate_config()
    except ConfigError as exc:
        logging.critical("%s. Сервер не запущено.", exc)
        raise

    _export_openapi_on_startup(app)

    yield  # Сервер працює


